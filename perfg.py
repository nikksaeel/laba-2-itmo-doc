def triangle (a, b, c):
    '''на вход получает значение переменных a, b, c (стороны треугольника).
    Возвращает числовое значение периметра фигуры.'''
    return a+b+c;

def rectungle (a, b):
    '''на вход получает значение переменных a, b (стороны прямоугольника). 
    Возвращает числовое значение периметра фигуры.'''
    return 2*(a+b)

def circle (r):
    '''на вход получает значение переменной r (радиус круга).
    Возвращает числовое значение периметра фигуры.'''
    return 2*3.14*r